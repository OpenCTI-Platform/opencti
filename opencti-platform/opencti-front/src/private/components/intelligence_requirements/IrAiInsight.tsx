import React, { useCallback, useEffect, useState } from 'react';
import { fetchQuery, graphql } from 'react-relay';
import { Combobox, ComboboxContent, ComboboxControls, ComboboxField, ComboboxInput, ComboboxTrigger, Tooltip, TooltipContent, TooltipTrigger } from '@filigran/design-system';
import { LogoXtmOneIcon } from 'filigran-icon';
import Button from '@common/button/Button';
import Drawer from '@components/common/drawer/Drawer';
import FiligranIcon from '@components/common/FiligranIcon';
import ValidateTermsOfUseDialog from '@components/settings/ValidateTermsOfUseDialog';
import XtmOneAISummaryDisplay from '@components/common/ai/XtmOneAISummaryDisplay';
import { useFormatter } from '../../../components/i18n';
import { environment } from '../../../relay/environment';
import useApiMutation from '../../../utils/hooks/useApiMutation';
import useAgentStream from '../../../utils/ai/useAgentStream';
import { type AgentOption, fetchAgentsForIntent } from '../../../utils/ai/agentApi';
import { getDefaultAiLanguage } from '../../../utils/ai/Common';
import useIrAiGate from './useIrAiGate';
import { cleanHtmlTags } from '../../../utils/utils';
import type { IrAiInsightPromptQuery } from './__generated__/IrAiInsightPromptQuery.graphql';
import type { IrAiInsightLegacyMutation } from './__generated__/IrAiInsightLegacyMutation.graphql';

// AI Insight of a requirement: a report question by question, written by an XTM One agent
// (or by the LLM configured on the platform when XTM One is not used).

// Dedicated intent first (once registered and bound to an agent in XTM One), the general assistant otherwise
const INTENTS = ['cti.pir_insight', 'global.assistant'];

const promptQuery = graphql`
  query IrAiInsightPromptQuery($id: ID!, $language: String, $referenceOnly: Boolean) {
    intelligenceRequirement(id: $id) {
      id
      ir_ai_prompt(language: $language, reference_only: $referenceOnly)
    }
  }
`;

const legacyMutation = graphql`
  mutation IrAiInsightLegacyMutation($id: ID!, $language: String) {
    intelligenceRequirementAiInsight(id: $id, language: $language)
  }
`;

const DISCLAIMER = 'This report is based on the entities of the requirement, their proofs and scores, and on its key intelligence questions. It has been generated by AI and can contain mistakes.';

// A dedicated agent reads the requirement with its tools: it only needs the reference.
// The general assistant has no such tools: it gets the content of the requirement in the prompt.
const XtmOneInsight = ({ irId, agent, dedicated }: { irId: string; agent: AgentOption | null; dedicated: boolean }) => {
  const { t_i18n } = useFormatter();
  // getDefaultAiLanguage reads a React context: it must run during render, not in a callback
  const language = getDefaultAiLanguage();
  const [promptError, setPromptError] = useState<string | null>(null);
  const [preparing, setPreparing] = useState(false);
  const { content, loading, error, generatedAt, execute } = useAgentStream({ transformContent: cleanHtmlTags });
  const run = useCallback((forceRefresh = false) => {
    if (!agent) return;
    setPromptError(null);
    setPreparing(true);
    fetchQuery<IrAiInsightPromptQuery>(environment, promptQuery, { id: irId, language, referenceOnly: dedicated }, { fetchPolicy: 'network-only' })
      .toPromise()
      .then((data) => {
        setPreparing(false);
        const prompt = data?.intelligenceRequirement?.ir_ai_prompt;
        if (!prompt) {
          setPromptError(t_i18n('Unable to prepare the content of the requirement.'));
          return;
        }
        execute(agent.slug, prompt, forceRefresh);
      })
      .catch(() => {
        setPreparing(false);
        setPromptError(t_i18n('Unable to prepare the content of the requirement.'));
      });
  }, [agent, irId, language, dedicated, execute]);
  useEffect(() => {
    run();
  }, [agent?.slug]);
  return (
    <XtmOneAISummaryDisplay
      disclaimerText={t_i18n(DISCLAIMER)}
      noAgent={!agent}
      errorMessage={promptError ?? error}
      loading={preparing || loading}
      content={content}
      generatedAt={generatedAt}
      onRetry={() => run(true)}
    />
  );
};

const LegacyInsight = ({ irId }: { irId: string }) => {
  const { t_i18n } = useFormatter();
  const language = getDefaultAiLanguage();
  const [commit, inFlight] = useApiMutation<IrAiInsightLegacyMutation>(legacyMutation);
  const [content, setContent] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [generatedAt, setGeneratedAt] = useState<string | null>(null);
  const run = useCallback(() => {
    setError(null);
    setContent('');
    commit({
      variables: { id: irId, language },
      onCompleted: (response) => {
        const answer = response.intelligenceRequirementAiInsight ?? '';
        if (answer.startsWith('An error occurred')) {
          setError(answer);
        } else {
          setContent(cleanHtmlTags(answer));
          setGeneratedAt(new Date().toISOString());
        }
      },
      onError: (e) => setError(e.message),
    });
  }, [irId, language, commit]);
  useEffect(() => {
    run();
  }, []);
  return (
    <XtmOneAISummaryDisplay
      disclaimerText={t_i18n(DISCLAIMER)}
      noAgent={false}
      errorMessage={error}
      loading={inFlight}
      content={content}
      generatedAt={generatedAt}
      onRetry={run}
    />
  );
};

const IrAiInsight = ({ irId }: { irId: string }) => {
  const { t_i18n } = useFormatter();
  const { visible, xtmOneConfigured, termsPending, disabledReason } = useIrAiGate('AI Insight');
  const [open, setOpen] = useState(false);
  const [termsOpen, setTermsOpen] = useState(false);
  const [agents, setAgents] = useState<AgentOption[]>([]);
  const [agent, setAgent] = useState<AgentOption | null>(null);
  const [agentIntent, setAgentIntent] = useState<string | null>(null);
  const [loadingAgents, setLoadingAgents] = useState(false);

  useEffect(() => {
    if (!open || !xtmOneConfigured) return;
    setLoadingAgents(true);
    (async () => {
      for (let i = 0; i < INTENTS.length; i += 1) {
        const found = await fetchAgentsForIntent(INTENTS[i]);
        if (found.length > 0) {
          setAgents(found);
          setAgentIntent(INTENTS[i]);
          // The OpenCTI specialist fits a CTI report better than a generic router
          setAgent((current) => current ?? found.find((a) => a.slug.includes('opencti')) ?? found[0]);
          break;
        }
      }
      setLoadingAgents(false);
    })();
  }, [open, xtmOneConfigured]);

  if (!visible) return null;

  const button = (
    <Button
      variant="tertiary"
      intent="ai"
      disabled={!!disabledReason}
      startIcon={<FiligranIcon icon={LogoXtmOneIcon} size={16} />}
      onClick={() => (termsPending ? setTermsOpen(true) : setOpen(true))}
    >
      {t_i18n('AI Insight')}
    </Button>
  );
  return (
    <>
      {disabledReason ? (
        <Tooltip>
          <TooltipTrigger asChild><span style={{ display: 'inline-flex' }}>{button}</span></TooltipTrigger>
          <TooltipContent>{disabledReason}</TooltipContent>
        </Tooltip>
      ) : button}
      {termsOpen && <ValidateTermsOfUseDialog open={termsOpen} onClose={() => setTermsOpen(false)} />}
      <Drawer
        open={open}
        onClose={() => setOpen(false)}
        title={t_i18n('AI Insight')}
        header={xtmOneConfigured ? (
          <Combobox<AgentOption>
            labelPosition="none"
            clearable={false}
            options={agents}
            getOptionLabel={(option) => option?.name ?? ''}
            value={agent}
            onValueChange={(next) => setAgent(next as AgentOption | null)}
            loading={loadingAgents}
            disabled={agents.length === 0}
          >
            <ComboboxField>
              <ComboboxInput aria-label={t_i18n('Select agent')} placeholder={agents.length === 0 ? t_i18n('No agent available') : t_i18n('Select agent')} />
              <ComboboxControls>
                <ComboboxTrigger />
              </ComboboxControls>
            </ComboboxField>
            <ComboboxContent emptyMessage={t_i18n('No agent available')} listAriaLabel={t_i18n('Select agent')} />
          </Combobox>
        ) : undefined}
      >
        {open && (xtmOneConfigured ? <XtmOneInsight irId={irId} agent={agent} dedicated={agentIntent === INTENTS[0]} /> : <LegacyInsight irId={irId} />)}
      </Drawer>
    </>
  );
};

export default IrAiInsight;
